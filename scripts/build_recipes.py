"""Generate references/recipe-library.md and simulations/common/recipes.js from curriculum/recipes.yaml.
Usage: py scripts/build_recipes.py
Merge recipe inboxes first: py scripts/build_recipes.py --merge   (appends new ids from curriculum/recipe-inbox/*.yaml)"""
import json, sys
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "curriculum/recipes.yaml"
FAMILIES = ["sour", "highball", "old-fashioned", "martini-manhattan", "spritz-sparkling", "collins-fizz",
            "tiki-punch", "savory", "coffee", "other"]
REQUIRED = ["id", "name", "family", "method", "glass", "ice", "garnish", "ingredients", "source", "lesson"]


def load():
    return yaml.safe_load(SRC.read_text(encoding="utf-8")) or []


def merge():
    recipes = load()
    ids = {r["id"] for r in recipes}
    added = 0
    for f in sorted((ROOT / "curriculum/recipe-inbox").glob("*.yaml")):
        for r in yaml.safe_load(f.read_text(encoding="utf-8")) or []:
            if r["id"] not in ids:
                recipes.append(r); ids.add(r["id"]); added += 1
    SRC.write_text(yaml.safe_dump(recipes, allow_unicode=True, sort_keys=False, width=110), encoding="utf-8", newline="\n")
    print(f"merged {added} new recipes")


def validate(recipes):
    errs, seen = [], set()
    for r in recipes:
        for k in REQUIRED:
            if k not in r: errs.append(f"{r.get('id')}: missing {k}")
        if r.get("id") in seen: errs.append(f"duplicate id {r['id']}")
        seen.add(r.get("id"))
        if r.get("family") not in FAMILIES: errs.append(f"{r.get('id')}: bad family {r.get('family')}")
    return errs


def oz(ml):
    q = round(ml / 30 * 4) / 4
    whole, frac = int(q), q - int(q)
    f = {0: "", 0.25: "¼", 0.5: "½", 0.75: "¾"}[frac]
    return (str(whole) if whole else "") + f if (whole or f) else "—"


def amount(i):
    if isinstance(i.get("ml"), (int, float)):
        return f"{i['ml']:g}", oz(i["ml"])
    return str(i.get("amount", i.get("ml", ""))), "—"


def lesson_link(lid):
    m, l = str(lid).split(".")
    return f"../lessons/module-{int(m):02d}/lesson-{int(l):02d}.md"


def library(recipes):
    out = ["# Recipe library", "",
           "Every cocktail spec taught in the course, A–Z, with the lesson that teaches it. IBA specs are the default; "
           "each lesson shows the common variations and their sources. Generated from one data file, so the specs here, "
           "in the lessons and in the simulations always match.", "",
           "| Drink | Family | Method | Glass | Lesson |", "|---|---|---|---|---|"]
    rs = sorted(recipes, key=lambda r: r["name"].lower())
    for r in rs:
        out.append(f"| [{r['name']}](#{r['id']}) | {r['family']} | {r['method']} | {r['glass']} | "
                   f"[{r['lesson']}]({lesson_link(r['lesson'])}) |")
    for r in rs:
        out += ["", f"## {r['name']}", "", "| Ingredient | ml | oz |", "|---|---|---|"]
        for i in r["ingredients"]:
            ml, o = amount(i)
            out.append(f"| {i['item']} | {ml} | {o} |")
        src = r["source"]
        out += ["", f"- **Method:** {r['method']}", f"- **Glass and ice:** {r['glass']}, {r['ice']}",
                f"- **Garnish:** {r['garnish']}", f"- **Spec source:** [{src['title']}]({src['url']})",
                f"- **Alcohol-free analogue:** {r.get('na_analogue') or 'none that is faithful'}",
                f"- **Taught in:** [lesson {r['lesson']}]({lesson_link(r['lesson'])})"]
    return "\n".join(out) + "\n"


def main():
    if "--merge" in sys.argv:
        merge()
    recipes = load()
    errs = validate(recipes)
    for e in errs: print("ERROR", e)
    if errs: sys.exit(1)
    (ROOT / "references/recipe-library.md").write_text(library(recipes), encoding="utf-8", newline="\n")
    js = ("/* Generated by scripts/build_recipes.py from curriculum/recipes.yaml. Do not edit. */\n"
          "(function (root) {\n  var RECIPES = " + json.dumps(recipes, ensure_ascii=False, indent=1) + ";\n"
          "  if (typeof module !== \"undefined\" && module.exports) module.exports = RECIPES;\n"
          "  else root.RECIPES = RECIPES;\n})(typeof window !== \"undefined\" ? window : globalThis);\n")
    (ROOT / "simulations/common/recipes.js").write_text(js, encoding="utf-8", newline="\n")
    print(f"{len(recipes)} recipes")


if __name__ == "__main__":
    main()
